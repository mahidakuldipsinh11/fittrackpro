TAGS = ["Bestseller", "New", "Deal", "Popular", "Trending", None, None, None]

import random

total = 0
for cat_name, products in CATS.items():
    cat, _ = Category.objects.get_or_create(name=cat_name)
    for name, price, was in products:
        Product.objects.create(
            name=name,
            category=cat,
            price=price,
            was_price=was,
            off_percent=round(((was - price) / was) * 100),
            description=f"Premium quality {name.lower()} for home and commercial gym use. Built to last with professional-grade materials.",
            image=random.choice(IMAGES),
            tag=random.choice(TAGS),
            is_deal=random.choice([True, False]),
            is_featured=random.choice([True, False]),
            stock=random.randint(5, 100),
        )
        total += 1

print(f"Created {total} products successfully!")
print(f"Categories: {Category.objects.count()}")
for c in Category.objects.all():
    count = Product.objects.filter(category=c).count()
    print(f"  {c.name}: {count}")
