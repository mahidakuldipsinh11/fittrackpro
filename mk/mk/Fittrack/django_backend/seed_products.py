def seed_products():
    print("\n========================================")
    print("       FITTRACK PRODUCT SEEDER")
    print("========================================\n")

    added = 0
    skipped = 0

    for data in PRODUCTS:
        category_name = data.pop("category")

        category, _ = Category.objects.get_or_create(
            name=category_name
        )

        product, created = Product.objects.get_or_create(
            name=data["name"],
            defaults={
                "category": category,
                "price": Decimal(str(data["price"])),
                "was_price": Decimal(str(data["was_price"])),
                "off_percent": data["off_percent"],
                "description": data["description"],
                "image": data["image"],
                "tag": data.get("tag"),
                "is_deal": data.get("is_deal", False),
                "is_featured": data.get("is_featured", False),
                "claimed": 0,
                "ends_in_hours": 48,
                "stock": data.get("stock", 0),
            },
        )

        if created:
            added += 1
            print(f"✅ Added: {product.name}")
        else:
            skipped += 1
            print(f"⏭️ Already exists: {product.name}")

    print("\n========================================")
    print(f"✅ Products added : {added}")
    print(f"⏭️ Already existed: {skipped}")
    print(f"📦 Total products : {Product.objects.count()}")
    print("========================================\n")


if __name__ == "__main__":
    seed_products()